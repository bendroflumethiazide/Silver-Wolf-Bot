"""Import Currency Wars icons (user-supplied, from the HSR Wiki) into public/cw/<kind>/<slug>.webp
and write src/lib/currencywars/iconIndex.ts (name -> file, with the manifest's "also used for" aliases).

Usage: python3 -I scripts/import-cw-icons.py <icons dir with manifest.csv> [<extra dir of PNGs, kind=item> ...]
"""
import csv, json, os, re, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KIND = {
    "Basic Equipment": "item", "Advanced/Privileged Equipment": "item", "Diamond & Treasure Gem": "item", "Trash Bag": "item",
    "Emblem": "item", "Meal Component": "item", "Express Component": "item", "Hacking Component": "item", "Fixed Equipment": "item",
    "Other": "item", "Consumables": "item", "Characters": "character", "Bonds": "bond", "Investment Environments": "environment",
    "Investment Strategies": "strategy", "Voyage Companions (standee art)": "companion", "Resources": "resource", "Elation and Misc": "misc",
}
slug = lambda n: re.sub(r"-+", "-", re.sub(r"[^a-z0-9]+", "-", n.lower().replace("★", "star").replace("•", "-"))).strip("-") or "x"

def save(src, kind, name, index):
    s = slug(name)
    out = os.path.join(ROOT, "public", "cw", kind, s + ".webp")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    im = Image.open(src)
    im = im.convert("RGBA")
    if max(im.size) > 160: im.thumbnail((160, 160), Image.LANCZOS)
    im.save(out, "WEBP", quality=88, method=6)
    index.setdefault(kind, {})[name] = s
    return s

def main():
    src_dir, extras = sys.argv[1], sys.argv[2:]
    index = {}
    for r in csv.DictReader(open(os.path.join(src_dir, "manifest.csv"), encoding="utf-8-sig")):
        kind = KIND.get(r["section"])
        if not kind: print("skip section", r["section"]); continue
        path = os.path.join(src_dir, *r["file"].split("\\"))
        name = r["name"].replace("Glo⬛!?", "Glo⬛!?")
        s = save(path, kind, name, index)
        for alias in [a.strip() for a in r["also used for"].split("|") if a.strip()]:
            index[kind].setdefault(alias, s)
    for d in extras:
        for f in sorted(os.listdir(d)):
            if f.lower().endswith((".png", ".webp", ".jpg")): save(os.path.join(d, f), "item", os.path.splitext(f)[0], index)
    # Gold Coins use the "Wealth" picture.
    index.setdefault("resource", {})["Gold Coin"] = "../item/" + index["item"]["Wealth"]
    body = json.dumps(index, ensure_ascii=False, indent=1, sort_keys=True)
    ts = ('/** Generated by scripts/import-cw-icons.py from the icons supplied by the user (HSR Wiki images). Do not edit by hand. */\n'
          'export const CW_ICON_INDEX: Record<string, Record<string, string>> = ' + body + ';\n')
    open(os.path.join(ROOT, "src", "lib", "currencywars", "iconIndex.ts"), "w", encoding="utf-8").write(ts)
    print({k: len(v) for k, v in index.items()})

main()
